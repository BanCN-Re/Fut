#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""gen_fake_cert.py - build a self-signed cert/key and emit it as a C header.

The fake server needs a TLS certificate. We embed it rather than shipping a PFX
file, because the whole point of the split architecture is to keep the on-disk
footprint small and unremarkable -- a stray .pfx next to zw_core.dll would be an
obvious artifact.

The certificate is deliberately generic (CN=localhost, no SAN for the blocked
domains) because certificate verification is bypassed by our own hooks; the cert
only has to complete a handshake, not pass a real chain check.

Outputs:
  cheat/src/fake_cert.h  - PEM cert + PEM key as string literals

Usage: python gen_fake_cert.py <out-header>
"""
import datetime
import sys

from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import rsa
from cryptography.x509.oid import NameOID


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "fake_cert.h"
    domains_file = sys.argv[2] if len(sys.argv) > 2 else None

    # The blocked hostnames go into the SAN list. This matters: the client
    # connects with SNI = the real report host (e.g. pc.crashsight.qq.com) and
    # then verifies the name against the certificate. A bare "*" SAN does NOT
    # satisfy OpenSSL for a multi-label name like pc.crashsight.qq.com -- "*"
    # matches a single label only. Listing the exact hosts is what makes the
    # hostname check pass.
    domains = []
    if domains_file:
        with open(domains_file, encoding="utf-8") as f:
            for line in f:
                d = line.strip()
                if d and not d.startswith("#"):
                    domains.append(d)

    key = rsa.generate_private_key(public_exponent=65537, key_size=2048)
    subject = issuer = x509.Name([
        x509.NameAttribute(NameOID.COUNTRY_NAME, "US"),
        x509.NameAttribute(NameOID.ORGANIZATION_NAME, "Local Service"),
        x509.NameAttribute(NameOID.COMMON_NAME, domains[0] if domains else "localhost"),
    ])

    sans = [x509.DNSName(d) for d in domains]
    if not sans:
        sans = [x509.DNSName("*")]

    now = datetime.datetime.now(datetime.timezone.utc)
    cert = (
        x509.CertificateBuilder()
        .subject_name(subject)
        .issuer_name(issuer)
        .public_key(key.public_key())
        .serial_number(x509.random_serial_number())
        .not_valid_before(now - datetime.timedelta(days=1))
        .not_valid_after(now + datetime.timedelta(days=3650))
        .add_extension(x509.SubjectAlternativeName(sans), critical=False)
        # Marked as a CA so the client can also treat it as its own issuer.
        .add_extension(x509.BasicConstraints(ca=True, path_length=None), critical=False)
        .sign(key, hashes.SHA256())
    )

    cert_pem = cert.public_bytes(serialization.Encoding.PEM).decode()
    key_pem = key.private_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PrivateFormat.PKCS8,
        encryption_algorithm=serialization.NoEncryption(),
    ).decode()

    def c_literal(text):
        lines = text.strip().splitlines()
        return "\n".join('    "%s\\n"' % ln for ln in lines)

    with open(out, "w", encoding="utf-8") as f:
        f.write("// Auto-generated by tools/gen_fake_cert.py -- DO NOT EDIT.\n")
        f.write("//\n")
        f.write("// Self-signed TLS material for the local fake report server. Verification\n")
        f.write("// is bypassed by our own hooks, so this cert only has to complete a\n")
        f.write("// handshake; it does not need to chain to a real CA.\n")
        f.write("//\n")
        f.write("// SAN is DNS:* so a stray hostname check still passes.\n")
        f.write("#pragma once\n\n")
        f.write("namespace fakecert {\n\n")
        f.write("static const char kCertPem[] =\n%s;\n\n" % c_literal(cert_pem))
        f.write("static const char kKeyPem[] =\n%s;\n\n" % c_literal(key_pem))
        f.write("} // namespace fakecert\n")

    print("wrote %s" % out)
    print("  cert: %d bytes PEM" % len(cert_pem))
    print("  key : %d bytes PEM (RSA-2048)" % len(key_pem))


if __name__ == "__main__":
    main()
