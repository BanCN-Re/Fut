# D:\Work\Fut\tools\webui\gen_fields.ps1
#
# Generates fields.ps1 from webui_shm.h.
#
# WHY THIS EXISTS
#   The reader addresses the shared block by byte offset. A hand-typed table drifts
#   the moment a field is added, and the failure is silent -- a slider writes into
#   an unrelated field. Generating the table from the C++ header makes that
#   impossible: the header is the single source of truth.
#
# USAGE
#   pwsh -File tools\webui\gen_fields.ps1            # print to stdout
#   pwsh -File tools\webui\gen_fields.ps1 -Write     # overwrite fields.ps1
#
# It parses the Params struct body, sums field sizes (pack(1) makes that exact),
# and emits the table with the 8-byte block prefix applied.
param([switch]$Write)

$ErrorActionPreference = 'Stop'

$headerPath = Join-Path $PSScriptRoot '..\..\cheat\src\webui_shm.h'
$headerPath = (Resolve-Path $headerPath).Path

$text = Get-Content $headerPath -Raw -Encoding UTF8

$i = $text.IndexOf('struct Params {')
if ($i -lt 0) { throw "struct Params not found in $headerPath" }
$j = $text.IndexOf('};', $i)
if ($j -lt 0) { throw "end of struct Params not found" }
$body = $text.Substring($i, $j - $i)

# pack(1) is asserted: without it the offsets are compiler-dependent and this
# generator would produce a table that only works for one build configuration.
if ($text -notmatch '#pragma pack\(push,\s*1\)') {
    throw "webui_shm.h must use #pragma pack(push, 1) -- offsets are otherwise unpredictable"
}

$PREFIX = 8      # 4-byte seq + 4-byte pad

$rows = @()
$off = 0
$names = @{}
foreach ($line in ($body -split "`r?`n")) {
    if ($line -match '^\s*(uint8_t|uint32_t|int32_t|float|char)\s+(\w+)(\[(\d+)\])?;') {
        $type = $Matches[1]
        $name = $Matches[2]
        $n = if ($Matches[4]) { [int]$Matches[4] } else { 1 }

        $tsize = 0
        switch ($type) {
            'uint8_t'  { $tsize = 1 }
            'int32_t'  { $tsize = 4 }
            'uint32_t' { $tsize = 4 }
            'float'    { $tsize = 4 }
            'char'     { $tsize = 1 }
            default    { throw "unhandled type '$type' for field '$name'" }
        }

        # Padding fields exist only to make the layout explicit; the reader has no
        # business addressing them.
        if ($name -notmatch '^_pad') {
            # NOTE: assigning inside `switch` without a default branch is a trap --
            # each matching branch's output is collected and the variable becomes
            # an Object[]. Every branch above assigns explicitly and there is a
            # default that throws, which is what keeps $kind a plain string.
            $kind = ''
            switch ($type) {
                'uint8_t'  { $kind = 'u8' }
                'int32_t'  { $kind = 'i32' }
                'uint32_t' { $kind = 'u32' }
                'float'    { $kind = 'f32' }
                'char'     { $kind = "str$n" }
                default    { throw "unhandled kind for '$name'" }
            }
            if ($names.ContainsKey($name)) { throw "duplicate field '$name' in Params" }
            $names[$name] = $true
            # PARENTHESES AROUND THE ARITHMETIC. Without them PowerShell parses
            #     @($name, $off + $PREFIX, $kind)
            # as an array whose second element is `$off` and which then continues
            # with `+ $PREFIX, $kind` -- producing a FOUR-element row
            # ('espEnabled', 0, 8, 'u8'). The reader then took index 2 ('8') as the
            # type tag. Caught by the tag check above, which is why that check
            # exists.
        # Guard: a declaration with a comma declares several fields and would be
        # silently skipped, shifting every later offset. Fail loudly instead.
        if ($line -match '^\s*(uint8_t|uint32_t|int32_t|float|char)\b[^;]*,[^;]*;') {
            throw "multi-variable declaration not supported (one field per line): $($line.Trim())"
        }

        $rows += ,@($name, ($off + $PREFIX), $kind)
        }

        $off += $tsize * $n
    }
}

$paramsSize = $off
$blockSize  = $paramsSize + $PREFIX

$out = New-Object System.Collections.ArrayList
[void]$out.Add('# D:\Work\Fut\tools\webui\fields.ps1')
[void]$out.Add('#')
[void]$out.Add('# GENERATED by tools\webui\gen_fields.ps1 from cheat\src\webui_shm.h.')
[void]$out.Add('# DO NOT EDIT BY HAND -- run the generator instead.')
[void]$out.Add('#')
[void]$out.Add('# The reader addresses the shared block by byte offset, so a table that')
[void]$out.Add('# drifts from the C++ struct does not fail loudly: a slider moves an')
[void]$out.Add('# unrelated field. Generating it removes that failure mode.')
[void]$out.Add('#')
[void]$out.Add("# Params: $paramsSize bytes, Block: $blockSize bytes (incl. ${PREFIX}-byte prefix)")
[void]$out.Add('')
[void]$out.Add('# name, blockOffset, type')
[void]$out.Add('$script:FIELDS = @(')

$lastKind = ''
foreach ($r in $rows) {
    # Explicit casts with PARENTHESES around the index.
    #
    # `[string]$r[2]` does NOT cast element 2 -- PowerShell binds the cast tighter
    # than the index, so it evaluates as `([string]$r)[2]`: the whole row is turned
    # into its text form first ("espEnabled 0 u8") and then indexed as a string.
    # The generated table came out with type tags like '8' and 'p' because of it.
    # That is a silent corruption of exactly the kind this generator exists to
    # prevent, so the parentheses are load-bearing.
    $name = [string]($r[0])
    $o    = [int]($r[1])
    $k    = [string]($r[2])
    if ($k -notmatch '^(u8|i32|u32|f32|str\d+)$') {
        throw "field '$name' has a corrupt type tag ('$k') -- generator bug"
    }

    # group headings purely for readability
    $group = if ($o -lt 48) { 'ESP' } elseif ($o -lt 92) { 'aim' } elseif ($o -lt 180) { 'status' } else { 'control' }
    if ($group -ne $lastKind) {
        [void]$out.Add("    # ---- $group ----")
        $lastKind = $group
    }
    # LEADING COMMA IS REQUIRED.
    #
    # Inside @( ), PowerShell FLATTENS nested array literals written as separate
    # statements. Emitting
    #     @('a',8,'u8')
    #     @('b',9,'u8')
    # produces one flat array of six elements, so the reader's `$f[0]` yields a
    # character rather than a field name -- measured as 63 bogus table entries
    # instead of 46 fields.
    #
    # The unary comma wraps each row so it survives as a single element:
    #     ,@('a',8,'u8')
    [void]$out.Add(("    ,@('{0}',{1},'{2}')" -f $name, $o, $k))
}
[void]$out.Add(')')
[void]$out.Add('')
[void]$out.Add("# Copy size for the reader. Rounded up: reading a few extra bytes is harmless")
[void]$out.Add("# and protects against the struct growing before this table is regenerated.")
[void]$out.Add("# The game refuses to publish anything larger than its own block, so this")
[void]$out.Add("# must stay >= $blockSize.")
[void]$out.Add('$script:BLOCK_SIZE = 256')

$result = ($out -join "`r`n")

if ($Write) {
    $target = Join-Path $PSScriptRoot 'fields.ps1'
    $result | Out-File $target -Encoding UTF8
    Write-Host "wrote $target ($($rows.Count) fields, Params=$paramsSize Block=$blockSize)"
} else {
    $result
}
